/** Materializa las fechas relativas a HOY (fecha del proyecto). */
export function paradasDemo() {
  const now = new Date()
  return RAW.map((p, i) => {
    let start: Date
    if (p.duracionMinReal == null) {
      // parada abierta: arrancó hace 30–150 min (para que "en curso" sea realista)
      start = new Date(now.getTime() - (30 + ((i * 37) % 120)) * 60000)
    } else {
      const base = new Date()
      base.setDate(base.getDate() - p.offsetDias)
      const fecha = fechaLocal(base)
      const [y, mo, dy] = fecha.split("-").map(Number)
      const [hh, mi, ss] = p.hora.split(":").map(Number)
      start = new Date(y, mo - 1, dy, hh, mi, ss)
    }
    const inicio = `${fechaLocal(start)}T${horaLocal(start)}`
    let fin: string | null = null
    if (p.duracionMinReal != null) {
      const end = new Date(start.getTime() + p.duracionMinReal * 60000)
      fin = `${fechaLocal(end)}T${horaLocal(end)}`
    }
    return {
      id: p.reporteId,
      categoria: p.categoria,
      pisoMin: p.pisoMin,
      area: p.area,
      turnoTipo: p.turnoTipo,
      turnoCodigo: null,
      linea: p.lineaCodigo,
      equipoCodigo: p.equipoCodigo,
      equipoNombre: p.equipoNombre,
      subsistemaCodigo: p.subsistemaCodigo,
      subsistemaNombre: p.subsistemaNombre,
      descripcion: p.descripcion,
      supervisorNombre: p.supervisorNombre,
      reporta: p.reporta,
      estatus: p.estatus,
      inicio,
      fin,
      procuraMin: p.procuraMin,
      downtimeSheetMin: p.downtimeSheetMin,
    }
  })
}
